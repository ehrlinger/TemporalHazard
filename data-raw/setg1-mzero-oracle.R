# --- The rewrite grid (#601): M x NU x FIX flags, on the mzero data. ---
# Every SETG1_mNuOne_FALSE() case with M in {-1, 0, 0.5} and NU in {-1, 0, 1},
# each with no flag, FIXM, FIXNU and both (the substitute review of #597). A
# job SETG1 refuses exits SEMANTIC and prints no "Initial Parameter Values"
# table, so its used/estimated columns are NA.
gg <- expand.grid(m = c(-1, 0, 0.5), nu = c(-1, 0, 1),
                  fl = c("", "FIXM", "FIXNU", "FIXM FIXNU"),
                  stringsAsFactors = FALSE)
grows <- lapply(seq_len(nrow(gg)), function(k) {
  parms <- trimws(sprintf("MUE=1 THALF=0.5 M=%g NU=%g %s", gg$m[k], gg$nu[k],
                          gg$fl[k]))
  out <- run_one(parms, sprintf("G%d", k), DM)
  has_table <- any(grepl("Initial Parameter Values", out, fixed = TRUE)) &&
    any(grepl("Based on the values used", out, fixed = TRUE))
  nu <- if (has_table) initial(out, "NU") else c(used = NA, estimated = NA)
  m <- if (has_table) initial(out, "M") else c(used = NA, estimated = NA)
  refused <- any(grepl("fatal exit: (SYNTAX|SEMANTIC)", out))
  v <- verdict(out)
  f <- final(out)
  data.frame(parms = parms, nu_used = as.numeric(nu[["used"]]),
             nu_estimated = nu[["estimated"]],
             m_used = as.numeric(m[["used"]]), m_estimated = m[["estimated"]],
             mzero = if (refused) "refused" else v[["verdict"]],
             mzero_code = v[["code"]], mzero_ll = f[["ll"]],
             mzero_thalf = f[["thalf"]], mzero_nu = f[["nu"]],
             mzero_m = f[["m"]], mzero_mue = f[["mue"]],
             stringsAsFactors = FALSE)
})
gtab <- do.call(rbind, grows)
