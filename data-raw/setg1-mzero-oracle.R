# Regenerate tests/testthat/fixtures/setg1-mzero-oracle.csv and
# tests/testthat/fixtures/setg1-mzero-data.csv (#471).
#
# What SETG1 does to an early phase that starts at M = 0 (setg1.c, pin
# dad7978), read off the HAZARD binary rather than the source:
#   M = 0, NU < 0 (:651-667) and M = 0, NU > 0 (:713-731): M is FIXED at 0,
#     unless NU is fixed and M free, when M is MOVED to 1 instead;
#   M = 0, NU = 0 with M fixed and NU free (:700-707): NU is MOVED to 1.
# The listing's "Initial Parameter Values" table prints the value each shape
# parameter is "Used" at and whether it is "Estimated?", after SETG1 and
# before any iteration, so it records the rewrite even when the fit then
# fails. Where the fit runs, the final log-likelihood and estimates are
# recorded too.
#
# Datasets:
#   "mzero"  300 rows drawn from the early phase itself at M = 0 (t_half 1,
#            nu 2, mu 2, censored at 20), so the M-fixed model has an interior
#            optimum. Drawn with hzr_decompos(), so this script loads the
#            package; the rows are written out (setg1-mzero-data.csv) and the
#            tests read them, never redraw them.
#   "ref"    avc (complete cases), as data-raw/setg1-oracle.R stages it;
#   "synth"  stream D's synthetic-n200-seed5, as data-raw/setg1-oracle.R.
# On ref and synth the M-fixed model has no interior optimum for these jobs:
# THALF runs off (to about 1e89 on synth, and past the overflow limit on avc,
# where the fit stops with DTRSFM1120, hzd_early_t2p.c:34-37). They are
# recorded for the outcome only.
#
# Run from the package root:  Rscript data-raw/setg1-mzero-oracle.R [hazard]

