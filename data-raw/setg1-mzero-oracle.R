run_one <- function(parms, ix, D) {
  haven::write_xpt(D, file.path(work, sprintf("hzr.J471.%s.dta", ix)),
                   version = 5, name = "HZRCALL")
  ctl <- file.path(work, sprintf("hzr.J471.%s.sas", ix))
  lst <- file.path(work, sprintf("hzr.J471.%s.lst", ix))
  writeLines(c(paste0("(   PROC HAZARD DATA=D; EVENT DEAD; TIME TT; PARMS ",
                      parms, ";   )"),
               sprintf("; OBSCOUNT %d ;", nrow(D)), "JOBID J471;",
               sprintf("JOBIX %s;", ix)), ctl)
  system(paste0("TMPDIR=", shQuote(work), " ", shQuote(bin), " < ",
                shQuote(ctl), " > ", shQuote(lst), " 2>&1"))
  readLines(lst, warn = FALSE)
}
num <- function(x) as.numeric(trimws(sub("^[;+@][0-9]*,?", "", x)))
# One parameter's row of the "Initial Parameter Values" table: the second
# number after the name is "Used", and the first Yes/No is "Estimated?".
initial <- function(out, name) {
  i0 <- grep("Initial Parameter Values", out, fixed = TRUE)[1L]
  i1 <- grep("Based on the values used", out, fixed = TRUE)[1L]
  stopifnot(!is.na(i0), !is.na(i1))
  s <- out[i0:i1]
  j <- which(s == paste0("+1,", name))[1L]
  stopifnot(!is.na(j))
  blk <- s[(j + 1L):min(length(s), j + 12L)]
  nums <- grep("^\\+[0-9]+, *-?[0-9.]+(E[-+][0-9]+)? *$", blk, value = TRUE)
  est <- grep(",(Yes|No) *$", blk, value = TRUE)[1L]
  c(used = num(nums[2L]), estimated = trimws(sub("^\\+[0-9]+,", "", est)))
}
final <- function(out) {
  i <- grep("Estimates for Model Parameters", out, fixed = TRUE)
  ll <- grep("Log likelihood", out, fixed = TRUE)
  if (!length(i) || !length(ll)) {
    return(c(ll = NA, thalf = NA, nu = NA, m = NA, mue = NA))
  }
  s <- out[i[length(i)]:length(out)]
  val <- function(pat) {
    j <- grep(pat, s)[1L]
    num(grep("^\\+7,", s[j:(j + 4L)], value = TRUE)[1L])
  }
  c(ll = num(out[ll[length(ll)] + 1L]), thalf = val("^@55,THALF"),
    nu = val("^@55,NU"), m = val("^@55,M *$"), mue = val("^ *\\+3,MUE"))
}
verdict <- function(out) {
  raised <- sub("^\\[hazard ERROR [^]]*\\] ", "",
                out[grepl("^\\[hazard ERROR", out)])
  code <- if (length(raised)) sub(" .*$", "", raised[[1L]]) else ""
  c(verdict = if (any(grepl("Estimates for Model Parameters", out,
                            fixed = TRUE)) && !nzchar(code)) "runs" else
    "no_result", code = code)
}

rows <- lapply(seq_along(grid), function(k) {
  om <- run_one(grid[[k]], sprintf("M%d", k), DM)
  o0 <- run_one(grid[[k]], sprintf("R%d", k), D0)
  o1 <- run_one(grid[[k]], sprintf("S%d", k), D1)
  nu <- initial(om, "NU")
  m <- initial(om, "M")
  vm <- verdict(om)
  fm <- final(om)
  data.frame(id = names(grid)[[k]], parms = grid[[k]],
             nu_used = as.numeric(nu[["used"]]), nu_estimated = nu[["estimated"]],
             m_used = as.numeric(m[["used"]]), m_estimated = m[["estimated"]],
             mzero = vm[["verdict"]], mzero_code = vm[["code"]],
             mzero_ll = fm[["ll"]], mzero_thalf = fm[["thalf"]],
             mzero_nu = fm[["nu"]], mzero_m = fm[["m"]], mzero_mue = fm[["mue"]],
             ref = verdict(o0)[["verdict"]], ref_code = verdict(o0)[["code"]],
             synth = verdict(o1)[["verdict"]], synth_code = verdict(o1)[["code"]],
             synth_ll = final(o1)[["ll"]], stringsAsFactors = FALSE)
})
